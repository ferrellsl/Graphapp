# Turns the original app's toolbar icons into icons.h, flattened on the toolbar's color.
# usage: make_icons.py <folder with the png files>   (needs Pillow)
import sys
from PIL import Image

NAMES = ["fileopen", "filecell", "savecontent", "movie", "box", "frame", "grid",
         "gridfr", "gridb", "gridr", "gridl", "gridc", "gridf",
         "scattered", "wireframe", "hiddenline", "polygon", "filledmesh", "nodata",
         "floordata", "flooriso", "floorempty", "normals"]
SIZE = 22

out = ["// Generated by make_icons.py from the QwtPlot3D example icons. RGB rows, top first.", ""]
for name in NAMES:
    img = Image.open(sys.argv[1] + "/" + name + ".png").convert("RGBA")
    if max(img.size) > SIZE:
        img = img.resize((SIZE, SIZE), Image.LANCZOS)
    flat = Image.new("RGBA", img.size, (240, 240, 240, 255))
    flat.alpha_composite(img)
    data = flat.convert("RGB").tobytes()
    out.append("static const unsigned char icon_%s[] = {" % name)
    for i in range(0, len(data), 24):
        out.append("".join("%d," % b for b in data[i:i+24]))
    out.append("};")
    out.append("enum { icon_%s_w = %d, icon_%s_h = %d };" % (name, img.width, name, img.height))
    out.append("")
open("icons.h", "w", newline="\n").write("\n".join(out))
